-- CMS Domain Data: referensi RAD berversi (seperti RAB/RAL), periode memakai versi RAD,
-- dan kolom data mengikuti template analis "Domain Arsitektur Data dan Informasi.xlsx".
-- Pohon RAD dibuat dari lib/data/rad-reference.json (node scripts/extract-rad.mjs --sql).

CREATE TABLE IF NOT EXISTS rad_versions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL UNIQUE,
  note text,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  based_on uuid REFERENCES rad_versions(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz
);

CREATE TABLE IF NOT EXISTS rad_references (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code text NOT NULL,
  name text NOT NULL,
  level int NOT NULL,
  parent_id uuid REFERENCES rad_references(id),
  version_id uuid NOT NULL REFERENCES rad_versions(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'berlaku' CHECK (status IN ('berlaku', 'tidak_berlaku')),
  origin_id uuid REFERENCES rad_references(id) ON DELETE SET NULL,
  UNIQUE (version_id, code)
);
CREATE INDEX IF NOT EXISTS rad_references_origin_idx ON rad_references (origin_id);
CREATE INDEX IF NOT EXISTS rad_references_parent_idx ON rad_references (parent_id);


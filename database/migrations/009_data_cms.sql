CREATE TABLE IF NOT EXISTS rad_changes (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  version_id uuid NOT NULL REFERENCES rad_versions(id) ON DELETE CASCADE,
  node_id uuid REFERENCES rad_references(id) ON DELETE SET NULL,
  action text NOT NULL,
  before jsonb,
  after jsonb,
  actor_name text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS rad_changes_version_idx ON rad_changes (version_id, created_at DESC);

-- Data & informasi: kolom template analis + alur verifikasi (Verifikator Data → Validator Diskominfo).
-- rad_id = RAD Level 3 (atau Level 2 yang tidak memiliki turunan); rad4_id/rad5_id terdaftar, rad_l4/rad_l5 isian bebas.
-- security = dependensi Keamanan SPBE (7 kunci → daftar teks) sampai modul Keamanan tersedia.
CREATE TABLE IF NOT EXISTS datasets (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  code text NOT NULL,
  name text NOT NULL,
  description text,
  purpose text,
  opd_id uuid NOT NULL REFERENCES opd(id),
  producer_opd_id uuid REFERENCES opd(id),
  producer text,
  output_info text,
  input_info text,
  sifat text NOT NULL CHECK (sifat IN ('terbuka', 'terbatas', 'tertutup')),
  jenis text NOT NULL CHECK (jenis IN ('statistik', 'geopasial', 'keuangan', 'lainnya')),
  validitas text NOT NULL,
  interoperable boolean NOT NULL DEFAULT false,
  period_id uuid NOT NULL REFERENCES architecture_periods(id),
  rad_id uuid REFERENCES rad_references(id),
  rad4_id uuid REFERENCES rad_references(id),
  rad5_id uuid REFERENCES rad_references(id),
  rad_l4 text,
  rad_l5 text,
  rad_review boolean NOT NULL DEFAULT false,
  security jsonb NOT NULL DEFAULT '{}',
  status submission_status NOT NULL DEFAULT 'draft',
  created_by uuid REFERENCES users(id),
  submitted_by uuid REFERENCES users(id),
  verified_by uuid REFERENCES users(id),
  approved_by uuid REFERENCES users(id),
  approved_at timestamptz,
  is_sample boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (code, period_id)
);
CREATE INDEX IF NOT EXISTS datasets_status_idx ON datasets (status);
CREATE INDEX IF NOT EXISTS datasets_opd_idx ON datasets (opd_id);
CREATE INDEX IF NOT EXISTS datasets_period_idx ON datasets (period_id);

CREATE TABLE IF NOT EXISTS dataset_process_businesses (
  dataset_id uuid NOT NULL REFERENCES datasets(id) ON DELETE CASCADE,
  process_business_id uuid NOT NULL REFERENCES process_businesses(id) ON DELETE CASCADE,
  PRIMARY KEY (dataset_id, process_business_id)
);
CREATE TABLE IF NOT EXISTS dataset_services (
  dataset_id uuid NOT NULL REFERENCES datasets(id) ON DELETE CASCADE,
  service_id uuid NOT NULL REFERENCES services(id) ON DELETE CASCADE,
  PRIMARY KEY (dataset_id, service_id)
);


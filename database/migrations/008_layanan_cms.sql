CREATE TABLE IF NOT EXISTS ral_versions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL UNIQUE,
  note text,
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  based_on uuid REFERENCES ral_versions(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz
);

ALTER TABLE ral_references
  ADD COLUMN IF NOT EXISTS version_id uuid REFERENCES ral_versions(id) ON DELETE CASCADE,
  ADD COLUMN IF NOT EXISTS status text NOT NULL DEFAULT 'berlaku',
  ADD COLUMN IF NOT EXISTS origin_id uuid REFERENCES ral_references(id) ON DELETE SET NULL;
DO $$ BEGIN
  ALTER TABLE ral_references ADD CONSTRAINT ral_references_status_check CHECK (status IN ('berlaku', 'tidak_berlaku'));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

